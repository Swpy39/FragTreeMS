def call_api_once(
    client: OpenAI,
    model: str,
    messages: List[Dict[str, str]],
    temperature: float,
    max_tokens: int,
    use_json_mode: bool = False,
) -> str:
    """Call Nuwa through its OpenAI-compatible Chat Completions endpoint."""
    kwargs: Dict[str, Any] = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "max_tokens": max_tokens,
    }
    if use_json_mode:
        kwargs["response_format"] = {"type": "json_object"}

    completion = client.chat.completions.create(**kwargs)
    content = completion.choices[0].message.content
    if content is None:
        raise ValueError("Nuwa returned an empty message content.")
    return content


def call_api_with_token_retry(
    client: OpenAI,
    model: str,
    messages: List[Dict[str, str]],
    temperature: float,
    use_json_mode: bool,
    base_max_tokens: int = 4096,
    api_retries: int = 3,
) -> Tuple[Optional[Dict[str, Any]], str, Optional[str]]:
    """Nuwa API + strict JSON parsing retries with increasing token budgets."""
    retry_count = max(1, int(api_retries))
    token_attempts: List[int] = []
    for multiplier in (1, 2, 4, 8):
        value = max(1024, int(base_max_tokens) * multiplier)
        if value not in token_attempts:
            token_attempts.append(value)
        if len(token_attempts) >= retry_count:
            break

    raw_text = ""
    last_error: Optional[str] = None

    for attempt, current_max_tokens in enumerate(token_attempts, start=1):
        try:
            print(
                f"[Nuwa Token Attempt {attempt}/{len(token_attempts)}] "
                f"max_tokens={current_max_tokens}"
            )
            raw_text = call_api_once(
                client=client,
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=current_max_tokens,
                use_json_mode=use_json_mode,
            )
            return extract_json_from_text(raw_text), raw_text, None

        except Exception as exc:
            last_error = str(exc)
            print(
                f"[Nuwa Token Attempt {attempt}/{len(token_attempts)}] failed: "
                f"{last_error}"
            )

            if use_json_mode and (
                "response_format" in last_error
                or "json" in last_error.lower()
                or "unsupported" in last_error.lower()
            ):
                try:
                    print(
                        f"[Nuwa fallback without JSON mode] "
                        f"max_tokens={current_max_tokens}"
                    )
                    raw_text = call_api_once(
                        client=client,
                        model=model,
                        messages=messages,
                        temperature=temperature,
                        max_tokens=current_max_tokens,
                        use_json_mode=False,
                    )
                    return extract_json_from_text(raw_text), raw_text, None
                except Exception as fallback_exc:
                    last_error = str(fallback_exc)
                    print(f"[Nuwa fallback failed] {last_error}")

            if attempt < len(token_attempts):
                time.sleep(3)

    return None, raw_text, last_error


def semantic_retry_if_needed(
    client: OpenAI,
    model: str,
    messages: List[Dict[str, str]],
    parsed: Optional[Dict[str, Any]],
    raw_text: str,
    temperature: float,
    use_json_mode: bool,
    max_retries: int,
    base_max_tokens: int = 4096,
    api_retries: int = 3,
) -> Tuple[Optional[Dict[str, Any]], str, List[str], bool]:
    """
    Retry when the model violates the no-delete / non-empty corrected_triplet schema.
    """
    if parsed is None:
        return parsed, raw_text, ["Initial parsed output is None."], False

    warnings = validate_judge_output(parsed)
    if not has_hard_format_error(warnings):
        return parsed, raw_text, warnings, False

    current_parsed = parsed
    current_raw = raw_text
    current_warnings = warnings

    for retry_idx in range(1, max_retries + 1):
        print(f"[Semantic Retry {retry_idx}/{max_retries}] hard warnings: {current_warnings}")

        retry_messages = messages + [
            {"role": "assistant", "content": current_raw},
            {
                "role": "user",
                "content": (
                    "Your previous JSON violates the required no-delete schema. "
                    "You must output strict JSON only. "
                    "verdict must be only 'accept' or 'revise'. "
                    "The verdict 'delete' is forbidden. "
                    "corrected_triplet must be a non-empty 3-element list. "
                    "Preserve the same target product ion as the original_triplet. "
                    "If the original precursor or mechanism is wrong, revise it using a valid "
                    "previous precursor candidate or a structure-driven smiles_fragment."
                ),
            },
        ]

        retry_parsed, retry_raw, retry_error = call_api_with_token_retry(
            client=client,
            model=model,
            messages=retry_messages,
            temperature=temperature,
            use_json_mode=use_json_mode,
            base_max_tokens=base_max_tokens,
            api_retries=api_retries,
        )

        if retry_parsed is None:
            current_warnings = [f"Semantic retry failed: {retry_error}"]
            continue

        retry_warnings = validate_judge_output(retry_parsed)
        current_parsed = retry_parsed
        current_raw = retry_raw
        current_warnings = retry_warnings

        if not has_hard_format_error(retry_warnings):
            return current_parsed, current_raw, current_warnings, True

    return current_parsed, current_raw, current_warnings, True


def build_corrected_outputs(
    input_records: List[Dict[str, Any]],
    full_results: List[Dict[str, Any]],
    include_unsafe_in_corrected: bool = False,
) -> List[Dict[str, Any]]:
    grouped: Dict[Any, Dict[str, Any]] = {}

    for record in input_records:
        data_id = record.get("id", None)
        grouped[data_id] = {
            "id": data_id,
            "name": record.get("name", ""),
            "smiles": record.get("smiles", ""),
            "formula": record.get("formula", ""),
            "mw": record.get("mw", ""),
            "corrected_triplet": [],
        }

    for item in full_results:
        data_id = item.get("id", None)
        if data_id not in grouped:
            grouped[data_id] = {
                "id": data_id,
                "name": item.get("name", ""),
                "smiles": item.get("smiles", ""),
                "formula": item.get("formula", ""),
                "mw": item.get("mw", ""),
                "corrected_triplet": [],
            }

        final_triplet = normalize_triplet(item.get("final_corrected_triplet"))

        if final_triplet is not None:
            grouped[data_id]["corrected_triplet"].append(final_triplet)

    return list(grouped.values())


def safe_int(value: Any) -> Optional[int]:
    try:
        return int(value)
    except Exception:
        try:
            return int(float(value))
        except Exception:
            return None


def canonical_id(value: Any) -> str:
    parsed = safe_int(value)
    return str(parsed) if parsed is not None else str(value).strip()


def triplet_identity(triplet: Any) -> Optional[str]:
    normalized = normalize_triplet(triplet)
    if normalized is None:
        return None
    return json.dumps(normalized, ensure_ascii=False, separators=(",", ":"))


def normalize_generated_triplet_list(value: Any) -> List[List[str]]:
    """Accept one direct triplet or the generation format's list of triplets."""
    direct = normalize_triplet(value)
    if direct is not None and all(not isinstance(x, (list, tuple, dict)) for x in value):
        return [direct]

    output: List[List[str]] = []
    if isinstance(value, list):
        for item in value:
            normalized = normalize_triplet(item)
            if normalized is not None:
                output.append(normalized)
    return output


def parse_mz_key(value: Any) -> Optional[int]:
    parsed = safe_int(value)
    if parsed is not None:
        return parsed
    match = re.search(r"m/z\s*(\d+)", str(value), flags=re.IGNORECASE)
    return int(match.group(1)) if match else None


def generation_results_to_judge_records(
    generation_results: Any,
) -> List[Dict[str, Any]]:
    """
    Convert repaired generation results into the original Judge input record format.

    Triplets are ordered by m/z descending. When one m/z contains multiple parallel
    triplets, their list order is retained.
    """
    if isinstance(generation_results, dict):
        generation_results = [generation_results]
    if not isinstance(generation_results, list):
        raise ValueError("generation_result_file must contain a list or one object.")

    records: List[Dict[str, Any]] = []
    for source in generation_results:
        if not isinstance(source, dict):
            continue

        model_output = source.get("model_output")
        if not isinstance(model_output, dict):
            model_output = {}
        triples = model_output.get("triples")
        if not isinstance(triples, dict):
            triples = {}

        mz_blocks: List[Tuple[int, int, Any]] = []
        for original_position, (mz_key, block) in enumerate(triples.items()):
            mz = parse_mz_key(mz_key)
            if mz is None:
                continue
            mz_blocks.append((mz, original_position, block))
        mz_blocks.sort(key=lambda x: (-x[0], x[1]))

        flattened_triplets: List[List[str]] = []
        source_locations: List[Dict[str, Any]] = []
        occurrence_by_mz: Dict[int, int] = defaultdict(int)

        for mz, _, block in mz_blocks:
            raw_triplets = block.get("triplet") if isinstance(block, dict) else None
            triplet_list = normalize_generated_triplet_list(raw_triplets)
            for triplet in triplet_list:
                occurrence = occurrence_by_mz[mz]
                occurrence_by_mz[mz] += 1
                flattened_triplets.append(triplet)
                source_locations.append({"mz": mz, "occurrence": occurrence})

        spectrum = source.get("input_spectrum")
        if not isinstance(spectrum, dict):
            spectrum = source.get("spectrum")
        if not isinstance(spectrum, dict):
            spectrum = {}

        record = {
            "id": source.get("id"),
            "name": source.get("name", ""),
            "smiles": source.get("smiles", model_output.get("smiles", "")),
            "formula": source.get("formula", model_output.get("formula", "")),
            "mw": source.get("mw", model_output.get("mw", "")),
            "compound_class": source.get("compound_class", ""),
            "spectrum": spectrum,
            "input_spectrum": spectrum,
            "triplets": flattened_triplets,
            "_source_locations": source_locations,
        }
        records.append(record)

    records.sort(
        key=lambda record: (
            0 if safe_int(record.get("id")) is not None else 1,
            safe_int(record.get("id"))
            if safe_int(record.get("id")) is not None
            else str(record.get("id")),
        )
    )
    return records


def filter_records(
    records: List[Dict[str, Any]],
    args: argparse.Namespace,
) -> List[Dict[str, Any]]:
    selected: List[Dict[str, Any]] = []
    for record in records:
        rid = safe_int(record.get("id"))
        if ID_MIN is not None and (rid is None or rid < ID_MIN):
            continue
        if ID_MAX is not None and (rid is None or rid > ID_MAX):
            continue
        selected.append(record)

    if LIMIT is None:
        return selected[START:]
    return selected[START:START + LIMIT]


def build_required_targets(records: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    targets: List[Dict[str, Any]] = []
    global_order = 0
    for record in records:
        source_locations = record.get("_source_locations", [])
        triplets = record.get("triplets", [])
        for triplet_index, triplet in enumerate(triplets):
            normalized = normalize_triplet(triplet)
            if normalized is None:
                continue
            product = parse_ion(normalized[2])
            source_location = (
                source_locations[triplet_index]
                if triplet_index < len(source_locations)
                else {}
            )
            mz = (
                product.get("mz")
                if product is not None
                else source_location.get("mz")
            )
            targets.append({
                "global_order": global_order,
                "id_key": canonical_id(record.get("id")),
                "record": record,
                "triplet_index": triplet_index,
                "triplet": normalized,
                "triplet_key": triplet_identity(normalized),
                "mz": mz,
                "occurrence": source_location.get("occurrence", 0),
                "item": None,
            })
            global_order += 1
    return targets


def valid_existing_judge_item(
    item: Any,
    target_mz: Optional[int],
    retry_existing_fallback: bool,
) -> bool:
    if not isinstance(item, dict):
        return False
    if retry_existing_fallback and item.get("auto_fallback_used", False):
        return False

    final_triplet = normalize_triplet(item.get("final_corrected_triplet"))
    if final_triplet is None:
        judge_output = item.get("judge_output")
        if isinstance(judge_output, dict):
            final_triplet = normalize_triplet(judge_output.get("corrected_triplet"))
    if final_triplet is None:
        return False

    if target_mz is not None:
        product = parse_ion(final_triplet[2])
        if product is None or product.get("mz") != target_mz:
            return False
    return True


def match_existing_judge_results(
    targets: List[Dict[str, Any]],
    existing_results: List[Dict[str, Any]],
    retry_existing_fallback: bool,
) -> List[Dict[str, Any]]:
    """
    Match old/new Judge entries to repaired-generation triplets.

    Priority:
      1. Same molecule + exact original_triplet.
      2. Same molecule + same target m/z, consuming occurrences one by one.

    Invalid old entries matching a target are consumed and replaced rather than
    being preserved as duplicate legacy extras.
    """
    by_id: Dict[str, List[int]] = defaultdict(list)
    for index, item in enumerate(existing_results):
        if isinstance(item, dict):
            by_id[canonical_id(item.get("id"))].append(index)

    used: set = set()
    consumed_invalid: set = set()

    for target in targets:
        candidates = by_id.get(target["id_key"], [])
        exact_candidates: List[int] = []
        for index in candidates:
            if index in used or index in consumed_invalid:
                continue
            item = existing_results[index]
            if triplet_identity(item.get("original_triplet")) == target["triplet_key"]:
                exact_candidates.append(index)

        chosen: Optional[int] = None
        for index in exact_candidates:
            if valid_existing_judge_item(
                existing_results[index], target.get("mz"), retry_existing_fallback
            ):
                chosen = index
                break

        if chosen is None and exact_candidates:
            consumed_invalid.add(exact_candidates[0])

        if chosen is None:
            for index in candidates:
                if index in used or index in consumed_invalid:
                    continue
                item = existing_results[index]
                original = normalize_triplet(item.get("original_triplet"))
                if original is None:
                    continue
                product = parse_ion(original[2])
                if product is None or product.get("mz") != target.get("mz"):
                    continue
                if valid_existing_judge_item(
                    item, target.get("mz"), retry_existing_fallback
                ):
                    chosen = index
                    break
                consumed_invalid.add(index)
                break

        if chosen is not None:
            used.add(chosen)
            copied = copy.deepcopy(existing_results[chosen])
            copied["triplet_index"] = target["triplet_index"]
            target["item"] = copied

    extras: List[Dict[str, Any]] = []
    for index, item in enumerate(existing_results):
        if index not in used and index not in consumed_invalid and isinstance(item, dict):
            extras.append(copy.deepcopy(item))
    return extras


def render_merged_output(
    targets: List[Dict[str, Any]],
    extras: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    ordered: List[Dict[str, Any]] = []
    for target in targets:
        item = target.get("item")
        if isinstance(item, dict):
            copied = copy.deepcopy(item)
            copied["triplet_index"] = target["triplet_index"]
            ordered.append(copied)
    ordered.extend(copy.deepcopy(extras))
    return ordered


def previous_context_for_target(
    targets: List[Dict[str, Any]],
    current_target: Dict[str, Any],
) -> Tuple[List[List[str]], List[List[str]]]:
    verified: List[List[str]] = []
    reliable: List[List[str]] = []
    for target in targets:
        if target["global_order"] >= current_target["global_order"]:
            break
        if target["id_key"] != current_target["id_key"]:
            continue
        item = target.get("item")
        if not isinstance(item, dict):
            continue
        final_triplet = normalize_triplet(item.get("final_corrected_triplet"))
        if final_triplet is None:
            continue
        if item.get("context_safe", False):
            verified.append(final_triplet)
            if (
                item.get("context_reliable_for_precursor", False)
                or is_reliable_for_precursor_context(final_triplet)
            ):
                reliable.append(final_triplet)
    return verified, reliable


def default_failure_log_path(output_file: str) -> str:
    stem, extension = os.path.splitext(output_file)
    return stem + "_repair_log.json"


def load_failure_log(path: str) -> Dict[str, Any]:
    if os.path.exists(path):
        try:
            loaded = load_json(path)
            if isinstance(loaded, dict):
                loaded.setdefault("records", {})
                return loaded
        except Exception as exc:
            print(f"[Failure log warning] Could not load {path}: {exc}")
    return {"records": {}}


def failure_key(target: Dict[str, Any]) -> str:
    return (
        f"{target['id_key']}|{target['triplet_index']}|"
        f"{target.get('mz')}|{target.get('occurrence', 0)}"
    )


def record_failure(
    failure_log: Dict[str, Any],
    target: Dict[str, Any],
    error: str,
    raw_response: str,
    attempt: int,
) -> int:
    key = failure_key(target)
    records = failure_log.setdefault("records", {})
    entry = records.setdefault(key, {
        "id": target["record"].get("id"),
        "triplet_index": target["triplet_index"],
        "mz": target.get("mz"),
        "occurrence": target.get("occurrence", 0),
        "original_triplet": target["triplet"],
        "failure_count": 0,
        "resolved": False,
        "fallback_used": False,
        "history": [],
    })
    entry["failure_count"] = int(entry.get("failure_count", 0)) + 1
    entry["resolved"] = False
    entry["history"].append({
        "failure_no": entry["failure_count"],
        "repair_attempt": attempt,
        "time": datetime.now().isoformat(timespec="seconds"),
        "error": str(error),
        "raw_response_tail": str(raw_response)[-4000:],
    })
    return entry["failure_count"]


def mark_resolved(
    failure_log: Dict[str, Any],
    target: Dict[str, Any],
    fallback_used: bool,
) -> None:
    key = failure_key(target)
    records = failure_log.setdefault("records", {})
    entry = records.setdefault(key, {
        "id": target["record"].get("id"),
        "triplet_index": target["triplet_index"],
        "mz": target.get("mz"),
        "occurrence": target.get("occurrence", 0),
        "original_triplet": target["triplet"],
        "failure_count": 0,
        "history": [],
    })
    entry["resolved"] = True
    entry["fallback_used"] = bool(fallback_used)
    entry["resolved_time"] = datetime.now().isoformat(timespec="seconds")


def build_result_item_for_missing_target(
    client: OpenAI,
    args: argparse.Namespace,
    target: Dict[str, Any],
    previous_verified: List[List[str]],
    previous_reliable: List[List[str]],
    failure_log: Dict[str, Any],
) -> Dict[str, Any]:
    record = target["record"]
    normalized_triplet = target["triplet"]
    data_id = record.get("id")
    name = record.get("name", "")
    smiles = record.get("smiles", "")
    formula = record.get("formula", "")
    mw = record.get("mw", "")

    previous_before_current = previous_verified[:]
    previous_reliable_before_current = previous_reliable[:]

    base_user_prompt = build_user_prompt(
        record=record,
        triplet=normalized_triplet,
        triplet_index=target["triplet_index"],
        previous_verified_corrected_triplets=previous_before_current,
        previous_reliable_precursor_triplets=previous_reliable_before_current,
    )
    repair_instruction = (
        "\n\n[Missing-Judge repair requirement]\n"
        "This triplet exists in the repaired Stage-1 generation file but has no valid "
        "corresponding entry in the previous detailed Judge file. Judge exactly this "
        "triplet now. Keep all original Judge chemistry rules unchanged. verdict must "
        "be accept or revise; corrected_triplet must be a non-empty three-string list; "
        "delete and an empty corrected_triplet are forbidden. Preserve the same target "
        "product ion."
    )
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": base_user_prompt + repair_instruction},
    ]

    parsed: Optional[Dict[str, Any]] = None
    raw_text = ""
    error: Optional[str] = None
    warnings: List[str] = []
    parse_ok = False
    semantic_retry_used = False
    model_judge_output_before_fallback: Optional[Dict[str, Any]] = None
    original_model_verdict = None

    for repair_attempt in range(1, max(1, REPAIR_ATTEMPTS) + 1):
        print(
            f"[Judge repair attempt {repair_attempt}/{max(1, REPAIR_ATTEMPTS)}] "
            f"id={data_id}, triplet_index={target['triplet_index']}, mz={target.get('mz')}"
        )
        parsed, raw_text, error = call_api_with_token_retry(
            client=client,
            model=MODEL,
            messages=messages,
            temperature=TEMPERATURE,
            use_json_mode=USE_JSON_MODE,
            base_max_tokens=MAX_TOKENS,
            api_retries=API_RETRIES,
        )
        parse_ok = parsed is not None

        if parsed is not None:
            parsed = enforce_current_record_metadata(
                parsed, record, normalized_triplet
            )
            parsed, raw_text, warnings, semantic_used = semantic_retry_if_needed(
                client=client,
                model=MODEL,
                messages=messages,
                parsed=parsed,
                raw_text=raw_text,
                temperature=TEMPERATURE,
                use_json_mode=USE_JSON_MODE,
                max_retries=SEMANTIC_RETRY,
                base_max_tokens=MAX_TOKENS,
                api_retries=API_RETRIES,
            )
            semantic_retry_used = semantic_retry_used or semantic_used

            if parsed is not None:
                parsed = enforce_current_record_metadata(
                    parsed, record, normalized_triplet
                )
                model_judge_output_before_fallback = copy.deepcopy(parsed)
                original_model_verdict = parsed.get("verdict")
                parsed = normalize_revise_without_change(parsed)
                parsed = enforce_current_record_metadata(
                    parsed, record, normalized_triplet
                )
                warnings = validate_judge_output(parsed)
                if not has_hard_format_error(warnings):
                    break

        failure_reason = error or "; ".join(warnings) or "Invalid Judge output."
        count = record_failure(
            failure_log=failure_log,
            target=target,
            error=failure_reason,
            raw_response=raw_text,
            attempt=repair_attempt,
        )
        print(
            f"[Judge repair rejected] id={data_id}, mz={target.get('mz')}, "
            f"failure_count={count}: {failure_reason}"
        )
        messages = messages + [
            {"role": "assistant", "content": raw_text or "{}"},
            {
                "role": "user",
                "content": (
                    "The previous repair answer is still invalid. Errors: "
                    + failure_reason
                    + ". Return the same strict Judge JSON schema. Do not delete. "
                    "corrected_triplet must be non-empty and must preserve the target ion."
                ),
            },
        ]
        parsed = None

    auto_fallback_used = False
    if parsed is None or has_hard_format_error(warnings):
        parsed = make_fallback_judge_output(
            record=record,
            original_triplet=normalized_triplet,
            previous_verified_triplets=previous_verified,
            reason_prefix=(
                "Nuwa did not return a valid no-delete Judge result after all repair attempts."
            ),
        )
        parsed = enforce_current_record_metadata(parsed, record, normalized_triplet)
        warnings = validate_judge_output(parsed)
        auto_fallback_used = True

    final_corrected = normalize_triplet(parsed.get("corrected_triplet"))
    if final_corrected is None:
        final_corrected = fallback_corrected_triplet(
            record, normalized_triplet, previous_verified
        )
        auto_fallback_used = True

    model_corrected_before_postprocess = normalize_triplet(
        parsed.get("corrected_triplet")
    )
    final_corrected = sanitize_triplet(
        triplet=final_corrected,
        record=record,
        previous_verified_triplets=previous_reliable,
    )
    final_corrected = restore_supported_original_dehydrogenation(
        original_triplet=normalized_triplet,
        final_triplet=final_corrected,
        previous_reliable_precursor_triplets=previous_reliable,
    )

    triplet_postprocess_modified = (
        model_corrected_before_postprocess is not None
        and final_corrected != model_corrected_before_postprocess
    )
    verdict_postprocess_modified = (
        original_model_verdict is not None
        and original_model_verdict != parsed.get("verdict")
    )
    postprocess_modified = (
        triplet_postprocess_modified or verdict_postprocess_modified
    )

    context_safe, chemical_warnings = is_context_safe_triplet(
        triplet=final_corrected,
        previous_verified_triplets=previous_reliable,
        smiles=smiles,
        molecule_formula=formula,
    )
    context_reliable = (
        context_safe and is_reliable_for_precursor_context(final_corrected)
    )

    mark_resolved(failure_log, target, auto_fallback_used)

    return {
        "id": data_id,
        "name": name,
        "smiles": smiles,
        "formula": formula,
        "mw": mw,
        "triplet_index": target["triplet_index"],
        "original_triplet": normalized_triplet,
        "judge_output": parsed,
        "model_judge_output_before_fallback": model_judge_output_before_fallback,
        "final_corrected_triplet": final_corrected,
        "auto_fallback_used": auto_fallback_used,
        "semantic_retry_used": semantic_retry_used,
        "postprocess_modified": postprocess_modified,
        "triplet_postprocess_modified": triplet_postprocess_modified,
        "verdict_postprocess_modified": verdict_postprocess_modified,
        "context_reliable_for_precursor": context_reliable,
        "raw_response": raw_text,
        "parse_ok": parse_ok,
        "error": None if parse_ok else error,
        "warnings": warnings,
        "chemical_warnings": chemical_warnings,
        "context_safe": context_safe,
        "previous_verified_corrected_triplets_before_current": previous_before_current,
        "previous_reliable_precursor_triplets_before_current": previous_reliable_before_current,
    }


def main() -> None:
    if os.path.abspath(CURRENT_JUDGE_FILE) == os.path.abspath(OUTPUT_FILE):
        raise ValueError(
            "--output_file must differ from --current_judge_file so the old file stays unchanged."
        )
    if not os.path.exists(INPUT_FILE):
        raise FileNotFoundError(INPUT_FILE)
    if not os.path.exists(CURRENT_JUDGE_FILE):
        raise FileNotFoundError(CURRENT_JUDGE_FILE)

    api_key = (
        args.api_key
        or os.environ.get("NUWA_API_KEY")
        or os.environ.get("OPENAI_API_KEY")
    )
    if not api_key:
        raise ValueError(
            "Nuwa API key is missing. Pass --api_key or set NUWA_API_KEY."
        )

    client = OpenAI(api_key=api_key, base_url=BASE_URL)

    generation_results = load_json(INPUT_FILE)
    all_records = generation_results_to_judge_records(generation_results)
    selected_records = filter_records(all_records, args)
    targets = build_required_targets(selected_records)

    if os.path.exists(OUTPUT_FILE):
        existing_results = load_json(OUTPUT_FILE)
        print(f"Loaded resumable merged output: {OUTPUT_FILE}")
    else:
        os.makedirs(os.path.dirname(OUTPUT_FILE) or ".", exist_ok=True)
        shutil.copy2(CURRENT_JUDGE_FILE, OUTPUT_FILE)
        existing_results = load_json(OUTPUT_FILE)
        print(
            f"Copied read-only old Judge file to new output:\n"
            f"  source={CURRENT_JUDGE_FILE}\n"
            f"  output={OUTPUT_FILE}"
        )

    if not isinstance(existing_results, list):
        raise ValueError("Current/new detailed Judge file must contain a JSON list.")

    extras = match_existing_judge_results(
        targets=targets,
        existing_results=existing_results,
        retry_existing_fallback=RETRY_EXISTING_FALLBACK,
    )

    failure_log_file = (
        FAILURE_LOG_FILE
        if FAILURE_LOG_FILE
        else default_failure_log_path(OUTPUT_FILE)
    )
    failure_log = load_failure_log(failure_log_file)

    missing_targets = [target for target in targets if target.get("item") is None]
    matched_count = len(targets) - len(missing_targets)

    print("=" * 92)
    print(f"Generation result:             {INPUT_FILE}")
    print(f"Read-only old Judge file:      {CURRENT_JUDGE_FILE}")
    print(f"New merged Judge file:         {OUTPUT_FILE}")
    print(f"New grouped corrected file:    {CORRECTED_OUTPUT_FILE}")
    print(f"Failure log:                   {failure_log_file}")
    print(f"Nuwa base URL:                 {BASE_URL}")
    print(f"Model:                          {MODEL}")
    print(f"Selected molecules:             {len(selected_records)}")
    print(f"Required generated triplets:    {len(targets)}")
    print(f"Already Judge-matched:          {matched_count}")
    print(f"Missing triplets to Judge:      {len(missing_targets)}")
    print(f"Unmatched legacy extras kept:   {len(extras)}")
    print("Matching: id + exact original_triplet; fallback id + target m/z occurrence")
    print("Saving: rewrite the complete new output after every newly Judged triplet")
    print("=" * 92)

    merged_output = render_merged_output(targets, extras)
    save_json(merged_output, OUTPUT_FILE)
    corrected_outputs = build_corrected_outputs(
        input_records=selected_records,
        full_results=merged_output,
        include_unsafe_in_corrected=INCLUDE_UNSAFE_IN_CORRECTED,
    )
    save_json(corrected_outputs, CORRECTED_OUTPUT_FILE)
    save_json(failure_log, failure_log_file)

    completed_new = 0
    for target in targets:
        if target.get("item") is not None:
            continue

        completed_new += 1
        record = target["record"]
        previous_verified, previous_reliable = previous_context_for_target(
            targets, target
        )

        print("-" * 92)
        print(
            f"[Missing Judge {completed_new}/{len(missing_targets)}] "
            f"id={record.get('id')}, triplet_index={target['triplet_index']}, "
            f"m/z={target.get('mz')}, triplet={target['triplet']}"
        )
        print(
            f"Previous verified context={len(previous_verified)}, "
            f"reliable precursor context={len(previous_reliable)}"
        )

        new_item = build_result_item_for_missing_target(
            client=client,
            args=args,
            target=target,
            previous_verified=previous_verified,
            previous_reliable=previous_reliable,
            failure_log=failure_log,
        )
        target["item"] = new_item

        merged_output = render_merged_output(targets, extras)
        save_json(merged_output, OUTPUT_FILE)
        corrected_outputs = build_corrected_outputs(
            input_records=selected_records,
            full_results=merged_output,
            include_unsafe_in_corrected=INCLUDE_UNSAFE_IN_CORRECTED,
        )
        save_json(corrected_outputs, CORRECTED_OUTPUT_FILE)
        save_json(failure_log, failure_log_file)

        print(
            f"[Inserted + full rewrite] id={record.get('id')}, "
            f"triplet_index={target['triplet_index']}, m/z={target.get('mz')}, "
            f"fallback={new_item.get('auto_fallback_used')}, output={OUTPUT_FILE}"
        )

        if SLEEP_SECONDS > 0:
            time.sleep(SLEEP_SECONDS)

    final_output = render_merged_output(targets, extras)
    save_json(final_output, OUTPUT_FILE)
    final_corrected = build_corrected_outputs(
        input_records=selected_records,
        full_results=final_output,
        include_unsafe_in_corrected=INCLUDE_UNSAFE_IN_CORRECTED,
    )
    save_json(final_corrected, CORRECTED_OUTPUT_FILE)
    save_json(failure_log, failure_log_file)

    unresolved = sum(
        1 for target in targets
        if not isinstance(target.get("item"), dict)
    )
    fallback_count = sum(
        1 for target in targets
        if isinstance(target.get("item"), dict)
        and target["item"].get("auto_fallback_used", False)
    )

    print("=" * 92)
    print("All done.")
    print(f"Detailed Judge entries:        {len(final_output)}")
    print(f"Newly Judged missing entries:  {completed_new}")
    print(f"Still unresolved:              {unresolved}")
    print(f"Fallback entries in output:    {fallback_count}")
    print(f"Old Judge source unchanged:    {CURRENT_JUDGE_FILE}")
    print(f"Merged Judge output:           {OUTPUT_FILE}")
    print(f"Grouped corrected output:      {CORRECTED_OUTPUT_FILE}")
    print(f"Failure log:                   {failure_log_file}")

if __name__ == "__main__":
    main()
