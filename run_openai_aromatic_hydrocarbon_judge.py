def build_corrected_outputs(
    input_records: List[Dict[str, Any]],
    full_results: List[Dict[str, Any]],
    include_unsafe_in_corrected: bool = False,
) -> List[Dict[str, Any]]:
    grouped: Dict[Any, Dict[str, Any]] = {}

    for record in input_records:
        data_id = record.get("id", None)
        grouped[data_id] = {
            "id": data_id,
            "name": record.get("name", ""),
            "smiles": record.get("smiles", ""),
            "formula": record.get("formula", ""),
            "mw": record.get("mw", ""),
            "corrected_triplet": [],
        }

    for item in full_results:
        data_id = item.get("id", None)
        if data_id not in grouped:
            grouped[data_id] = {
                "id": data_id,
                "name": item.get("name", ""),
                "smiles": item.get("smiles", ""),
                "formula": item.get("formula", ""),
                "mw": item.get("mw", ""),
                "corrected_triplet": [],
            }

        final_triplet = normalize_triplet(item.get("final_corrected_triplet"))

        # No-delete output policy:
        # context_safe only controls whether a triplet can be reused as later context.
        # It must not filter the final corrected_output_file, otherwise unsafe triplets
        # would be silently removed and behave like delete.
        if final_triplet is not None:
            grouped[data_id]["corrected_triplet"].append(final_triplet)

    return list(grouped.values())


