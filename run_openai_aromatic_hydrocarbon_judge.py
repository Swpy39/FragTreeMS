def call_api_once(
    client: OpenAI,
    model: str,
    messages: List[Dict[str, str]],
    temperature: float,
    max_tokens: int,
    use_json_mode: bool = False,
) -> str:
    """
    Official OpenAI API call using the Responses API.

    The command-line argument is still named max_tokens to keep all existing
    retry logic and commands unchanged; it is mapped to max_output_tokens here.
    """
    kwargs = {
        "model": model,
        "input": messages,
        "temperature": temperature,
        "max_output_tokens": max_tokens,
    }

    # Optional JSON mode for the official Responses API.
    # If unsupported in your environment, the existing retry logic will retry without it.
    if use_json_mode:
        kwargs["text"] = {"format": {"type": "json_object"}}

    response = client.responses.create(**kwargs)

    if hasattr(response, "output_text") and response.output_text:
        return response.output_text

    parts = []
    for item in getattr(response, "output", []) or []:
        for content in getattr(item, "content", []) or []:
            text = getattr(content, "text", None)
            if text:
                parts.append(text)

    if parts:
        return "\n".join(parts)

    return str(response)


def call_api_with_token_retry(
    client: OpenAI,
    model: str,
    messages: List[Dict[str, str]],
    temperature: float,
    use_json_mode: bool,
) -> Tuple[Optional[Dict[str, Any]], str, Optional[str]]:
    token_attempts = [2048, 4096, 8192]
    raw_text = ""
    last_error = None

    for attempt, current_max_tokens in enumerate(token_attempts, start=1):
        try:
            print(f"[Token Attempt {attempt}/{len(token_attempts)}] max_tokens={current_max_tokens}")
            raw_text = call_api_once(
                client=client,
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=current_max_tokens,
                use_json_mode=use_json_mode,
            )
            parsed = extract_json_from_text(raw_text)
            return parsed, raw_text, None

        except Exception as e:
            last_error = str(e)
            print(
                f"[Token Attempt {attempt}/{len(token_attempts)}] "
                f"API or JSON parsing failed with max_tokens={current_max_tokens}: {last_error}"
            )

            if use_json_mode and ("response_format" in last_error or "json" in last_error.lower()):
                try:
                    print(f"[Fallback without json mode] max_tokens={current_max_tokens}")
                    raw_text = call_api_once(
                        client=client,
                        model=model,
                        messages=messages,
                        temperature=temperature,
                        max_tokens=current_max_tokens,
                        use_json_mode=False,
                    )
                    parsed = extract_json_from_text(raw_text)
                    return parsed, raw_text, None
                except Exception as e2:
                    last_error = str(e2)
                    print(f"[Fallback without json mode failed] {last_error}")

            if attempt < len(token_attempts):
                time.sleep(3)

    return None, raw_text, last_error


def semantic_retry_if_needed(
    client: OpenAI,
    model: str,
    messages: List[Dict[str, str]],
    parsed: Optional[Dict[str, Any]],
    raw_text: str,
    temperature: float,
    use_json_mode: bool,
    max_retries: int,
) -> Tuple[Optional[Dict[str, Any]], str, List[str], bool]:
    """
    Retry when the model violates the no-delete / non-empty corrected_triplet schema.
    """
    if parsed is None:
        return parsed, raw_text, ["Initial parsed output is None."], False

    warnings = validate_judge_output(parsed)
    if not has_hard_format_error(warnings):
        return parsed, raw_text, warnings, False

    current_parsed = parsed
    current_raw = raw_text
    current_warnings = warnings

    for retry_idx in range(1, max_retries + 1):
        print(f"[Semantic Retry {retry_idx}/{max_retries}] hard warnings: {current_warnings}")

        retry_messages = messages + [
            {"role": "assistant", "content": current_raw},
            {
                "role": "user",
                "content": (
                    "Your previous JSON violates the required no-delete schema. "
                    "You must output strict JSON only. "
                    "verdict must be only 'accept' or 'revise'. "
                    "The verdict 'delete' is forbidden. "
                    "corrected_triplet must be a non-empty 3-element list. "
                    "Preserve the same target product ion as the original_triplet. "
                    "If the original precursor or mechanism is wrong, revise it using a valid "
                    "previous precursor candidate or a structure-driven smiles_fragment."
                ),
            },
        ]

        retry_parsed, retry_raw, retry_error = call_api_with_token_retry(
            client=client,
            model=model,
            messages=retry_messages,
            temperature=temperature,
            use_json_mode=use_json_mode,
        )

        if retry_parsed is None:
            current_warnings = [f"Semantic retry failed: {retry_error}"]
            continue

        retry_warnings = validate_judge_output(retry_parsed)
        current_parsed = retry_parsed
        current_raw = retry_raw
        current_warnings = retry_warnings

        if not has_hard_format_error(retry_warnings):
            return current_parsed, current_raw, current_warnings, True

    return current_parsed, current_raw, current_warnings, True


