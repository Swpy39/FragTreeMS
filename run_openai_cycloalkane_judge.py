def is_context_safe_triplet(
    triplet: List[str],
    previous_verified_triplets: List[List[str]],
    smiles: str,
    molecule_formula: str,
) -> Tuple[bool, List[str]]:
    reasons: List[str] = []

    if not isinstance(triplet, list) or len(triplet) != 3:
        return False, ["Triplet is not a valid 3-element list."]

    precursor, mechanism, product_ion = triplet
    product = parse_ion(product_ion)

    if product is None:
        return False, ["Cannot parse product ion formula/mz."]

    if not product.get("has_unknown") and product["nominal_mass"] != product["mz"]:
        reasons.append(
            f"Product ion formula/mz mismatch: formula={product['formula']}, "
            f"nominal_mass={product['nominal_mass']}, mz={product['mz']}."
        )

    mol_counts = parse_formula_counts(molecule_formula)
    mol_c = mol_counts.get("C", 0)
    if mol_c > 0 and product["carbon"] > mol_c:
        reasons.append(
            f"Product ion carbon number C{product['carbon']} exceeds molecule carbon number C{mol_c}."
        )

    if should_avoid_sigma_for_unsaturated_product(mechanism, product_ion):
        reasons.append(
            "Plain Sigma-bond cleavage is not safe as context for a highly unsaturated "
            "hydrocarbon ion; prefer same-carbon dehydrogenation when available."
        )

    precursor_mz = parse_precursor_mz(precursor)

    if isinstance(precursor, str) and precursor.startswith("smiles_fragment:"):
        best_fragment, alternatives = parse_smiles_fragment_precursor(precursor)
        all_fragments = [best_fragment] + alternatives
        valid_fragments = [frag for frag in all_fragments if frag and frag in smiles]

        if not valid_fragments:
            reasons.append(f"No smiles_fragment candidate is a substring of source SMILES '{smiles}'.")
        else:
            if best_fragment not in valid_fragments:
                reasons.append(
                    f"Best smiles_fragment '{best_fragment}' is invalid, although valid alternatives exist: {valid_fragments}."
                )

            if best_fragment:
                frag_c = count_c_in_smiles(best_fragment)
                prod_c = product["carbon"]

                if prod_c > 0 and frag_c < prod_c:
                    reasons.append(
                        f"Best smiles_fragment carbon number C{frag_c} is smaller than product ion carbon number C{prod_c}."
                    )

                # For sigma-bond cleavage, an exact-carbon fragment is safer for context memory.
                if mechanism == "Sigma-bond cleavage" and prod_c > 0 and frag_c != prod_c:
                    reasons.append(
                        f"For Sigma-bond cleavage, best smiles_fragment carbon number C{frag_c} should match product ion carbon number C{prod_c} for safe context use."
                    )

    if precursor_mz is not None:
        previous_ions = find_previous_ions_by_mz(previous_verified_triplets, precursor_mz)

        if not previous_ions:
            reasons.append(f"precursor_mz:{precursor_mz} is not supported by previous verified corrected triplets.")

        if mechanism == "Dehydrogenation / Sequential dehydrogenation" and previous_ions:
            same_carbon_higher_h_exists = any(
                prev_ion["carbon"] == product["carbon"]
                and prev_ion["hydrogen"] > product["hydrogen"]
                for prev_ion in previous_ions
            )
            if not same_carbon_higher_h_exists:
                reasons.append(
                    "Invalid dehydrogenation: precursor and product do not preserve carbon number "
                    "or precursor does not have a higher hydrogen count."
                )

        if mechanism == "Sigma-bond cleavage":
            reasons.append(
                "Sigma-bond cleavage with precursor_mz is not safe as sequential context; "
                "prefer structure-driven smiles_fragment for Sigma-bond cleavage."
            )

    return len(reasons) == 0, reasons


def sanitize_triplet(
    triplet: List[str],
    record: Dict[str, Any],
    previous_verified_triplets: List[List[str]],
) -> List[str]:
    """
    Deterministic cleanup after the LLM judge.

    This version is intentionally conservative: it fixes hard chemical/formula
    errors found in the uploaded cycloalkane results, but it does not rewrite a
    reasonable ring-cleavage explanation merely for stylistic preference.
    """
    precursor, mechanism, product_ion = triplet
    smiles = record.get("smiles", "")
    molecule_formula = record.get("formula", "")

    # 1) Repair formula/mz mismatch while preserving m/z.
    repaired_product_ion = repair_product_ion_formula_mz(product_ion, molecule_formula)
    if repaired_product_ion != product_ion:
        product_ion = repaired_product_ion

    product = parse_ion(product_ion)
    if product is None:
        return [precursor, mechanism, product_ion]

    # 2) Isotopic peak is not valid for M-1 style hydrocarbon ions such as
    # C7H10+• (m/z 93). After formula repair, treat same-carbon H-loss as
    # dehydrogenation if possible; otherwise fall back to ring cleavage.
    if mechanism == "Isotopic peak":
        mol_counts = parse_formula_counts(molecule_formula)
        if is_hydrocarbon_counts(mol_counts) and product["mz"] <= nominal_mass(mol_counts):
            chosen_mz = choose_dehydrogenation_precursor(
                original_precursor=precursor,
                previous_verified_triplets=previous_verified_triplets,
                product_ion=product_ion,
            )
            if chosen_mz is not None:
                return [
                    f"precursor_mz: {chosen_mz}",
                    "Dehydrogenation / Sequential dehydrogenation",
                    product_ion,
                ]
            if mol_counts.get("C", 0) == product["carbon"] and mol_counts.get("H", 0) > product["hydrogen"]:
                return [
                    f"smiles_fragment: {smiles}",
                    "Dehydrogenation / Sequential dehydrogenation",
                    product_ion,
                ]
            return [precursor, "Ring cleavage / Ring rearrangement", product_ion]

    # 3) In pure hydrocarbon cycloalkanes, broad "Neutral loss" should not be
    # used for generic hydrocarbon cation formation.
    if should_avoid_neutral_loss_for_hydrocarbon(
        mechanism=mechanism,
        product_ion=product_ion,
        molecule_formula=molecule_formula,
    ):
        replacement = choose_neutral_loss_replacement_mechanism(
            precursor=precursor,
            product_ion=product_ion,
            previous_verified_triplets=previous_verified_triplets,
            molecule_formula=molecule_formula,
        )
        return [precursor, replacement, product_ion]

    # 4) For primary/common cycloalkane ring ions, keep/recover ring cleavage
    # rather than forcing dehydrogenation or sigma cleavage.
    if is_common_cycloalkane_ring_fragment(product):
        if mechanism in {"Sigma-bond cleavage", "Neutral loss"}:
            return [precursor, "Ring cleavage / Ring rearrangement", product_ion]

    # 5) Avoid plain Sigma-bond cleavage for highly unsaturated hydrocarbon ions
    # only when the product is not a primary/common cycloalkane ring fragment.
    if should_avoid_sigma_for_unsaturated_product(mechanism, product_ion) and not is_common_cycloalkane_ring_fragment(product):
        chosen_mz = choose_dehydrogenation_precursor(
            original_precursor=precursor,
            previous_verified_triplets=previous_verified_triplets,
            product_ion=product_ion,
        )
        if chosen_mz is not None:
            return [
                f"precursor_mz: {chosen_mz}",
                "Dehydrogenation / Sequential dehydrogenation",
                product_ion,
            ]

        if isinstance(precursor, str) and precursor.startswith("smiles_fragment:"):
            return [precursor, "Ring cleavage / Ring rearrangement", product_ion]

        candidates = get_structure_fragment_candidates(smiles, product_ion)
        if candidates:
            return [format_smiles_fragment_candidate(candidates), "Ring cleavage / Ring rearrangement", product_ion]

    # 6) Fix structure-driven sigma precursor if a better exact-carbon candidate exists.
    # Do not apply this to Ring cleavage, because for cycloalkanes a full-ring or
    # parent-skeleton smiles_fragment can be a source marker rather than an exact
    # neutral precursor.
    if mechanism == "Sigma-bond cleavage" and isinstance(precursor, str) and precursor.startswith("smiles_fragment:"):
        candidates = get_structure_fragment_candidates(smiles, product_ion)
        best_fragment, _ = parse_smiles_fragment_precursor(precursor)
        best_c = count_c_in_smiles(best_fragment) if best_fragment else 0

        if candidates and (
            best_fragment not in smiles
            or best_c < product["carbon"]
            or best_c != product["carbon"]
        ):
            return [format_smiles_fragment_candidate(candidates), mechanism, product_ion]

    # 7) Fix unsupported dehydrogenation precursor_mz.
    if mechanism == "Dehydrogenation / Sequential dehydrogenation":
        precursor_mz = parse_precursor_mz(precursor)
        prev_ions = find_previous_ions_by_mz(previous_verified_triplets, precursor_mz) if precursor_mz else []

        supported = any(
            ion["carbon"] == product["carbon"] and ion["hydrogen"] > product["hydrogen"]
            for ion in prev_ions
        )
        if not supported:
            chosen_mz = choose_dehydrogenation_precursor(
                original_precursor=precursor,
                previous_verified_triplets=previous_verified_triplets,
                product_ion=product_ion,
            )
            if chosen_mz is not None:
                return [
                    f"precursor_mz: {chosen_mz}",
                    "Dehydrogenation / Sequential dehydrogenation",
                    product_ion,
                ]
            # If not supported, carbon-changing or unsupported same-carbon paths
            # should not be kept as dehydrogenation in cycloalkanes.
            return [precursor, "Ring cleavage / Ring rearrangement", product_ion]

    return [precursor, mechanism, product_ion]


def fallback_corrected_triplet(
    record: Dict[str, Any],
    original_triplet: List[str],
    previous_verified_triplets: List[List[str]],
) -> List[str]:
    """
    Deterministic no-delete fallback. It always returns a non-empty 3-element triplet.

    Compared with the previous version, this fallback first repairs impossible
    product formula/mz pairs and then chooses a cycloalkane-aware mechanism.
    """
    smiles = record.get("smiles", "")
    formula = record.get("formula", "")
    product_ion = repair_product_ion_formula_mz(original_triplet[2], formula)
    product = parse_ion(product_ion)

    if product is None:
        return [f"smiles_fragment: {smiles}", "Ring cleavage / Ring rearrangement", product_ion]

    mol_counts = parse_formula_counts(formula)
    if mol_counts and product["counts"] == mol_counts:
        return [f"smiles_fragment: {smiles}", "Molecular ion", product_ion]

    # Same-carbon higher-H precursor from verified context.
    chosen_mz = choose_dehydrogenation_precursor(
        original_precursor=original_triplet[0],
        previous_verified_triplets=previous_verified_triplets,
        product_ion=product_ion,
    )
    if chosen_mz is not None and not is_primary_cycloalkane_ring_ion(product):
        return [
            f"precursor_mz: {chosen_mz}",
            "Dehydrogenation / Sequential dehydrogenation",
            product_ion,
        ]

    # Structure-driven candidate with exact carbon count.
    frag_cands = get_structure_fragment_candidates(smiles, product_ion)
    precursor = format_smiles_fragment_candidate(frag_cands) if frag_cands else f"smiles_fragment: {smiles}"

    if is_alkyl_like_ion(product):
        mechanism = "Sigma-bond cleavage"
    else:
        mechanism = "Ring cleavage / Ring rearrangement"

    return [precursor, mechanism, product_ion]


def _clean_llm_text_field(value: Any) -> str:
    """Return a non-empty model-provided text field when available."""
    if value is None:
        return ""
    text = str(value).strip()
    return text


def make_fallback_judge_output(
    record: Dict[str, Any],
    original_triplet: List[str],
    previous_verified_triplets: List[List[str]],
    reason_prefix: str,
    model_reason: Optional[str] = None,
    model_overall_quality: Optional[str] = None,
    model_major_errors: Optional[List[Any]] = None,
    model_recommended_strategy: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Build a schema-valid no-delete fallback while preserving the model-written
    reason whenever the model returned one.

    Important:
    - The judge prompt is not changed.
    - If the model output contains a usable reason, that reason is kept as the
      final judge_output['reason'].
    - Deterministic fallback text is used only when no model-written reason exists,
      which can happen after API/JSON parsing failure or a severely malformed reply.
    """
    corrected = fallback_corrected_triplet(record, original_triplet, previous_verified_triplets)
    corrected = sanitize_triplet(corrected, record, previous_verified_triplets)

    llm_reason = _clean_llm_text_field(model_reason)
    if not llm_reason:
        llm_reason = (
            f"{reason_prefix} For this cycloalkane EI-MS triplet, "
            "a no-delete fallback was applied to preserve the target product ion "
            "and produce a chemically plausible precursor/mechanism."
        )

    llm_overall_quality = _clean_llm_text_field(model_overall_quality)
    if not llm_overall_quality:
        llm_overall_quality = (
            "Automatically revised by the cycloalkane no-delete fallback after "
            "the model response could not be used as a valid strict JSON judge output."
        )

    if isinstance(model_major_errors, list) and model_major_errors:
        major_errors = model_major_errors
    else:
        major_errors = [
            "Cycloalkane judge output was invalid, empty, or used a forbidden delete/empty corrected_triplet."
        ]

    llm_recommended_strategy = _clean_llm_text_field(model_recommended_strategy)
    if not llm_recommended_strategy:
        llm_recommended_strategy = (
            "Use the fallback corrected_triplet for the cycloalkane / alicyclic EI-MS record, "
            "and inspect chemical_warnings/context_safe before reusing it as later precursor context."
        )

    return {
        "id": record.get("id", None),
        "name": record.get("name", ""),
        "smiles": record.get("smiles", ""),
        "formula": record.get("formula", ""),
        "mw": record.get("mw", ""),
        "original_triplet": original_triplet,
        "verdict": "revise",
        "reason": llm_reason,
        "corrected_triplet": corrected,
        "overall_quality": llm_overall_quality,
        "major_errors": major_errors,
        "recommended_strategy": llm_recommended_strategy,
    }


