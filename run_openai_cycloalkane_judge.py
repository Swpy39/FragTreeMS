def filter_records(records: List[Dict[str, Any]], args: argparse.Namespace) -> List[Dict[str, Any]]:
    selected = []
    for record in records:
        rid_raw = record.get("id", None)
        try:
            rid = int(rid_raw)
        except Exception:
            rid = None

        if args.id_min is not None and rid is not None and rid < args.id_min:
            continue
        if args.id_max is not None and rid is not None and rid > args.id_max:
            continue
        selected.append(record)

    if args.limit is None:
        return selected[args.start:]
    return selected[args.start:args.start + args.limit]


def main() -> None:
    args = parse_args()

    api_key = args.api_key or os.environ.get("OPENAI_API_KEY")
    if not api_key:
        raise ValueError("API key is missing. Please pass --api_key or set OPENAI_API_KEY.")

    client = OpenAI(api_key=api_key)

    records = load_json(args.input_file)
    if isinstance(records, dict):
        records = [records]
    if not isinstance(records, list):
        raise ValueError("Input JSON must be a list or a single dict.")

    selected_records = filter_records(records, args)

    full_results: List[Dict[str, Any]] = []
    processed_keys = set()
    existing_by_key: Dict[Tuple[Any, Any], Dict[str, Any]] = {}

    if args.skip_existing and os.path.exists(args.output_file):
        try:
            full_results = load_json(args.output_file)
            for item in full_results:
                key = (item.get("id"), item.get("triplet_index"))
                processed_keys.add(key)
                existing_by_key[key] = item
            print(f"Loaded {len(full_results)} existing judge results.")
        except Exception as e:
            print(f"Failed to load existing output file. Start from empty results. Error: {e}")
            full_results = []
            processed_keys = set()
            existing_by_key = {}

    total_triplets = sum(len(get_judge_triplets_from_record(r)) for r in selected_records if isinstance(r, dict))

    print("=" * 80)
    print(f"Total selected cycloalkane / alicyclic hydrocarbon molecules: {len(selected_records)}")
    print(f"Total triplets to judge: {total_triplets}")
    print(f"id_min={args.id_min}, id_max={args.id_max}, start={args.start}, limit={args.limit}")
    print(f"Model: {args.model}")
    print(f"Full output file: {args.output_file}")
    print(f"Corrected output file: {args.corrected_output_file}")
    print(f"include_unsafe_in_corrected: {args.include_unsafe_in_corrected}")
    print("=" * 80)

    judged_count = 0

    for record_idx, record in enumerate(selected_records, start=1):
        if not isinstance(record, dict):
            continue

        data_id = record.get("id", None)
        name = record.get("name", "")
        smiles = record.get("smiles", "")
        formula = record.get("formula", "")
        mw = record.get("mw", "")
        triplets = get_judge_triplets_from_record(record)
        record["_judge_triplets_flat"] = triplets

        previous_verified_corrected_triplets: List[List[str]] = []
        previous_reliable_precursor_triplets: List[List[str]] = []

        if not isinstance(triplets, list):
            print(f"[Skip] id={data_id}: triplets is not a list.")
            continue

        print("=" * 80)
        print(
            f"[Molecule {record_idx}/{len(selected_records)}] "
            f"id={data_id}, name={name}, smiles={smiles}, formula={formula}, mw={mw}, "
            f"triplets={len(triplets)}"
        )

        for triplet_index, triplet in enumerate(triplets):
            normalized_triplet = normalize_triplet(triplet)

            previous_before_current = previous_verified_corrected_triplets[:]
            previous_reliable_before_current = previous_reliable_precursor_triplets[:]

            if normalized_triplet is None:
                fallback = fallback_corrected_triplet(
                    record=record,
                    original_triplet=["", "Sigma-bond cleavage", ""],
                    previous_verified_triplets=previous_verified_corrected_triplets,
                )
                result_item = {
                    "id": data_id,
                    "name": name,
                    "smiles": smiles,
                    "formula": formula,
                    "mw": mw,
                    "triplet_index": triplet_index,
                    "original_triplet": triplet,
                    "judge_output": None,
                    "model_judge_output_before_fallback": None,
                    "final_corrected_triplet": fallback,
                    "auto_fallback_used": True,
                    "raw_response": "",
                    "parse_ok": False,
                    "error": "Invalid cycloalkane judge input triplet format; expected a 3-element EI-MS triplet list.",
                    "warnings": ["Invalid cycloalkane judge input triplet format."],
                    "chemical_warnings": ["Invalid cycloalkane judge input triplet format."],
                    "context_safe": False,
                    "context_reliable_for_precursor": False,
                    "triplet_postprocess_modified": False,
                    "verdict_postprocess_modified": False,
                    "previous_verified_corrected_triplets_before_current": previous_before_current,
                    "previous_reliable_precursor_triplets_before_current": previous_reliable_before_current,
                }
                full_results.append(result_item)
                continue

            key = (data_id, triplet_index)
            if args.skip_existing and key in processed_keys:
                print(f"[Skip existing] id={data_id}, triplet_index={triplet_index}")
                existing_item = existing_by_key.get(key)
                if existing_item:
                    final_triplet = normalize_triplet(existing_item.get("final_corrected_triplet"))
                    if final_triplet is not None and existing_item.get("context_safe", False):
                        previous_verified_corrected_triplets.append(final_triplet)
                        if existing_item.get("context_reliable_for_precursor", False) or is_reliable_for_precursor_context(final_triplet):
                            previous_reliable_precursor_triplets.append(final_triplet)
                continue

            judged_count += 1
            print("-" * 80)
            print(
                f"[Judge {judged_count}/{total_triplets}] "
                f"id={data_id}, triplet_index={triplet_index}, triplet={normalized_triplet}"
            )
            print(f"Previous verified corrected triplets available: {len(previous_verified_corrected_triplets)}")

            user_prompt = build_user_prompt(
                record=record,
                triplet=normalized_triplet,
                triplet_index=triplet_index,
                previous_verified_corrected_triplets=previous_before_current,
                previous_reliable_precursor_triplets=previous_reliable_before_current,
            )
            messages = [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ]

            parsed, raw_text, error = call_api_with_token_retry(
                client=client,
                model=args.model,
                messages=messages,
                temperature=args.temperature,
                use_json_mode=args.use_json_mode,
            )

            model_judge_output_before_fallback = None
            parse_ok = parsed is not None
            semantic_retry_used = False

            if parsed is not None:
                parsed, raw_text, warnings, semantic_retry_used = semantic_retry_if_needed(
                    client=client,
                    model=args.model,
                    messages=messages,
                    parsed=parsed,
                    raw_text=raw_text,
                    temperature=args.temperature,
                    use_json_mode=args.use_json_mode,
                    max_retries=args.semantic_retry,
                )
                if parsed is not None:
                    parsed = enforce_current_record_metadata(
                        parsed=parsed,
                        record=record,
                        original_triplet=normalized_triplet,
                    )
                    model_judge_output_before_fallback = copy.deepcopy(parsed)
                    original_model_verdict = parsed.get("verdict")
                    original_model_corrected = normalize_triplet(parsed.get("corrected_triplet"))
                    parsed = normalize_revise_without_change(parsed)
                    parsed = enforce_current_record_metadata(
                        parsed=parsed,
                        record=record,
                        original_triplet=normalized_triplet,
                    )
                    warnings = validate_judge_output(parsed)
                else:
                    original_model_verdict = None
                    original_model_corrected = None
            else:
                original_model_verdict = None
                original_model_corrected = None
                warnings = [error or "API/JSON parsing failed."]

            auto_fallback_used = False

            if parsed is None or has_hard_format_error(warnings):
                parsed = make_fallback_judge_output(
                    record=record,
                    original_triplet=normalized_triplet,
                    previous_verified_triplets=previous_verified_corrected_triplets,
                    reason_prefix="The API output was missing, invalid, or still used a forbidden delete/empty corrected_triplet after retry.",
                    model_reason=(model_judge_output_before_fallback or {}).get("reason") if isinstance(model_judge_output_before_fallback, dict) else None,
                    model_overall_quality=(model_judge_output_before_fallback or {}).get("overall_quality") if isinstance(model_judge_output_before_fallback, dict) else None,
                    model_major_errors=(model_judge_output_before_fallback or {}).get("major_errors") if isinstance(model_judge_output_before_fallback, dict) else None,
                    model_recommended_strategy=(model_judge_output_before_fallback or {}).get("recommended_strategy") if isinstance(model_judge_output_before_fallback, dict) else None,
                )
                parsed = enforce_current_record_metadata(
                    parsed=parsed,
                    record=record,
                    original_triplet=normalized_triplet,
                )
                warnings = validate_judge_output(parsed)
                auto_fallback_used = True

            # Final corrected triplet used for final output and context.
            final_corrected = normalize_triplet(parsed.get("corrected_triplet"))
            if final_corrected is None:
                final_corrected = fallback_corrected_triplet(
                    record=record,
                    original_triplet=normalized_triplet,
                    previous_verified_triplets=previous_verified_corrected_triplets,
                )
                auto_fallback_used = True

            model_corrected_before_postprocess = normalize_triplet(parsed.get("corrected_triplet"))

            final_corrected = sanitize_triplet(
                triplet=final_corrected,
                record=record,
                previous_verified_triplets=previous_reliable_precursor_triplets,
            )

            final_corrected = restore_supported_original_dehydrogenation(
                original_triplet=normalized_triplet,
                final_triplet=final_corrected,
                previous_reliable_precursor_triplets=previous_reliable_precursor_triplets,
            )

            triplet_postprocess_modified = (
                model_corrected_before_postprocess is not None
                and final_corrected != model_corrected_before_postprocess
            )
            verdict_postprocess_modified = (
                original_model_verdict is not None
                and parsed is not None
                and original_model_verdict != parsed.get("verdict")
            )
            postprocess_modified = triplet_postprocess_modified or verdict_postprocess_modified

            context_safe, chemical_warnings = is_context_safe_triplet(
                triplet=final_corrected,
                previous_verified_triplets=previous_reliable_precursor_triplets,
                smiles=smiles,
                molecule_formula=formula,
            )

            context_reliable_for_precursor = context_safe and is_reliable_for_precursor_context(final_corrected)

            if context_safe:
                previous_verified_corrected_triplets.append(final_corrected)
                if context_reliable_for_precursor:
                    previous_reliable_precursor_triplets.append(final_corrected)

            result_item = {
                "id": data_id,
                "name": name,
                "smiles": smiles,
                "formula": formula,
                "mw": mw,
                "triplet_index": triplet_index,
                "original_triplet": normalized_triplet,
                "judge_output": parsed,
                "model_judge_output_before_fallback": model_judge_output_before_fallback,
                "final_corrected_triplet": final_corrected,
                "auto_fallback_used": auto_fallback_used,
                "semantic_retry_used": semantic_retry_used,
                "postprocess_modified": postprocess_modified,
                "triplet_postprocess_modified": triplet_postprocess_modified,
                "verdict_postprocess_modified": verdict_postprocess_modified,
                "context_reliable_for_precursor": context_reliable_for_precursor,
                "raw_response": raw_text,
                "parse_ok": parse_ok,
                "error": None if parse_ok else error,
                "warnings": warnings,
                "chemical_warnings": chemical_warnings,
                "context_safe": context_safe,
                "previous_verified_corrected_triplets_before_current": previous_before_current,
                "previous_reliable_precursor_triplets_before_current": previous_reliable_before_current,
            }

            full_results.append(result_item)

            print(
                f"Success. verdict={parsed.get('verdict')} "
                f"warnings={len(warnings)} "
                f"chemical_warnings={len(chemical_warnings)} "
                f"context_safe={context_safe} "
                f"context_reliable_for_precursor={context_reliable_for_precursor} "
                f"auto_fallback_used={auto_fallback_used} "
                f"previous_verified_corrected_triplets={len(previous_verified_corrected_triplets)} "
                f"previous_reliable_precursor_triplets={len(previous_reliable_precursor_triplets)}"
            )
            if warnings:
                for w in warnings[:10]:
                    print(f"  [Warning] {w}")
            if chemical_warnings:
                for w in chemical_warnings[:10]:
                    print(f"  [Chemical Warning] {w}")

            if args.save_every > 0 and len(full_results) % args.save_every == 0:
                save_json(full_results, args.output_file)
                corrected_outputs = build_corrected_outputs(
                    input_records=selected_records,
                    full_results=full_results,
                    include_unsafe_in_corrected=args.include_unsafe_in_corrected,
                )
                save_json(corrected_outputs, args.corrected_output_file)
                print(f"Intermediate full results saved to: {args.output_file}")
                print(f"Intermediate corrected results saved to: {args.corrected_output_file}")

            if args.sleep > 0:
                time.sleep(args.sleep)

    save_json(full_results, args.output_file)
    corrected_outputs = build_corrected_outputs(
        input_records=selected_records,
        full_results=full_results,
        include_unsafe_in_corrected=args.include_unsafe_in_corrected,
    )
    save_json(corrected_outputs, args.corrected_output_file)

    print("=" * 80)
    print("All done.")
    print(f"Saved full judge results: {args.output_file}")
    print(f"Saved corrected triplets: {args.corrected_output_file}")


if __name__ == "__main__":
    main()
