def get_judge_triplets_from_record(record: Dict[str, Any]) -> List[List[str]]:
    """
    Extract judge input triplets without changing the external input format.

    Supported formats:
    1. Existing judge input: record["triplets"] = [[src, mech, product], ...]
    2. Generator result format in the uploaded result file:
       record["model_output"]["triples"][mz]["triplet"] = [[src, mech, product], ...]
    3. Corrected-style input: record["corrected_triplet"] = [...]

    The output format of this script is unchanged; this function only makes the
    reader robust to the nested cycloalkane generation result format.
    """
    raw = record.get("triplets")
    if isinstance(raw, list) and raw:
        out = []
        for item in raw:
            t = normalize_triplet(item)
            if t is not None:
                out.append(t)
        if out:
            return out

    raw = record.get("corrected_triplet")
    if isinstance(raw, list) and raw:
        out = []
        for item in raw:
            t = normalize_triplet(item)
            if t is not None:
                out.append(t)
        if out:
            return out

    triples_obj = None
    if isinstance(record.get("model_output"), dict):
        triples_obj = record["model_output"].get("triples")
    if triples_obj is None and isinstance(record.get("triples"), dict):
        triples_obj = record.get("triples")

    out: List[List[str]] = []
    if isinstance(triples_obj, dict):
        def _mz_sort_key(x: Any) -> Tuple[float, str]:
            try:
                return (float(x), str(x))
            except Exception:
                return (float("inf"), str(x))

        for mz_key in sorted(triples_obj.keys(), key=_mz_sort_key, reverse=True):
            block = triples_obj.get(mz_key)
            if not isinstance(block, dict):
                continue
            raw_triplet = block.get("triplet", [])
            if normalize_triplet(raw_triplet) is not None:
                out.append(normalize_triplet(raw_triplet))
                continue
            if isinstance(raw_triplet, list):
                for item in raw_triplet:
                    t = normalize_triplet(item)
                    if t is not None:
                        out.append(t)

    # Preserve order but remove exact duplicates.
    deduped: List[List[str]] = []
    seen = set()
    for t in out:
        key = json.dumps(t, ensure_ascii=False)
        if key in seen:
            continue
        seen.add(key)
        deduped.append(t)
    return deduped


